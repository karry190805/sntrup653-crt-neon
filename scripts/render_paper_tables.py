#!/usr/bin/env python3
"""Render PAPER_TABLES.md from the fresh CSVs in ../csv.

Kept deliberately simple: every numeric cell is read from a CSV, while the
surrounding prose states the measurement boundary.  No number is typed twice.
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CSV = os.path.join(HERE, "..", "csv")


def rows(name):
    with open(os.path.join(CSV, name), newline="") as fh:
        return list(csv.DictReader(fh))


def num(x, nd=3):
    return ("{:,.%df}" % nd).format(float(x))


def pct(x):
    return "%.2f%%" % float(x)


def main(out):
    t0 = rows("table0_platforms.csv")
    t1 = rows("table1_selection.csv")
    t2 = rows("table2_correctness.csv")
    t3 = rows("table3_pmu.csv")
    t3c = rows("table3_cache.csv")
    t4 = rows("table4_kem.csv")
    t5 = rows("table5_stage.csv")
    t6_all = rows("table6_ablation.csv")
    t6 = [r for r in t6_all if r["category"].startswith("FAST16")]
    t6c = [r for r in t6_all if r["category"].startswith("configuration")]
    t6b = rows("table6b_factor_status.csv")
    mem = rows("table7_memory.csv")
    tabs = rows("table7_tables.csv")
    ops = rows("table7_machine_ops.csv")
    t8 = rows("table8_positioning.csv")
    t8ref = rows("table8_references.csv")
    t9 = rows("table9_security.csv")

    L = []
    w = L.append
    w("# sntrup653 CRT — opt22 paper tables (fresh rerun)")
